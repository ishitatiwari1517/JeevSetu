// ─── VolunteerHoursReportScreen ───────────────────────────────────────────────
import React, { useCallback, useState } from 'react';
import { View, Text, StyleSheet, FlatList, TouchableOpacity, StatusBar, Share, RefreshControl } from 'react-native';
import { SafeAreaView } from 'react-native-safe-area-context';
import { useFocusEffect } from '@react-navigation/native';
import Icon from 'react-native-vector-icons/MaterialCommunityIcons';
import { COLORS, SPACING, RADIUS, SHADOW } from '../theme/colors';
import { listVolunteers } from '../services/volunteerService';
import { getOrganization } from '../services/orgService';

const VolunteerHoursReportScreen = ({ navigation }) => {
  const [volunteers, setVolunteers] = useState([]);
  const [org, setOrg]               = useState(null);
  const [refreshing, setRefreshing] = useState(false);

  const loadData = useCallback(async () => {
    try {
      const orgObj = await getOrganization();
      setOrg(orgObj);
      const vols = await listVolunteers(orgObj?.id || 'default');
      setVolunteers(vols.sort((a, b) => (b.totalHoursLogged || 0) - (a.totalHoursLogged || 0)));
    } catch (e) { console.warn(e); }
    finally { setRefreshing(false); }
  }, []);

  useFocusEffect(useCallback(() => { loadData(); }, [loadData]));

  const totalHours  = volunteers.reduce((s, v) => s + (v.totalHoursLogged || 0), 0);
  const totalShifts = volunteers.reduce((s, v) => s + (v.totalShiftsCompleted || 0), 0);

  const handleShare = async () => {
    const lines = [
      `VOLUNTEER HOURS REPORT`,
      `${org?.name || 'Shelter'} — ${new Date().toLocaleDateString('en-IN')}`,
      ``,
      `Total volunteers: ${volunteers.length}`,
      `Total hours: ${totalHours.toFixed(1)}`,
      `Total shifts: ${totalShifts}`,
      ``,
      ...volunteers.map(v => `${v.name}: ${(v.totalHoursLogged || 0).toFixed(1)} hrs, ${v.totalShiftsCompleted || 0} shifts`),
      ``,
      `Generated by JeevSetu`,
    ];
    await Share.share({ message: lines.join('\n'), title: 'Volunteer Hours' });
  };

  const maxHours = Math.max(...volunteers.map(v => v.totalHoursLogged || 0), 1);

  return (
    <SafeAreaView style={styles.safe} edges={['top']}>
      <StatusBar barStyle="dark-content" backgroundColor={COLORS.surface} />
      <View style={styles.topBar}>
        <TouchableOpacity onPress={() => navigation.goBack()} style={{ padding: 4 }}>
          <Icon name="arrow-left" size={22} color={COLORS.textPrimary} />
        </TouchableOpacity>
        <Text style={styles.topTitle}>Volunteer Hours</Text>
        <TouchableOpacity style={styles.shareBtn} onPress={handleShare}>
          <Icon name="share-variant" size={18} color="#fff" />
          <Text style={styles.shareBtnText}>Share</Text>
        </TouchableOpacity>
      </View>
      <FlatList
        data={volunteers}
        keyExtractor={v => v.id}
        contentContainerStyle={styles.list}
        showsVerticalScrollIndicator={false}
        refreshControl={<RefreshControl refreshing={refreshing} onRefresh={() => { setRefreshing(true); loadData(); }} tintColor={COLORS.brand} />}
        ListHeaderComponent={() => (
          <View>
            <View style={styles.summaryRow}>
              <View style={[styles.summaryBox, { backgroundColor: '#E0F2FE' }]}>
                <Text style={[styles.summaryVal, { color: '#0891B2' }]}>{totalHours.toFixed(1)}</Text>
                <Text style={styles.summaryLbl}>Total Hours</Text>
              </View>
              <View style={[styles.summaryBox, { backgroundColor: COLORS.brandLight }]}>
                <Text style={[styles.summaryVal, { color: COLORS.brand }]}>{totalShifts}</Text>
                <Text style={styles.summaryLbl}>Total Shifts</Text>
              </View>
              <View style={[styles.summaryBox, { backgroundColor: COLORS.healthyBg }]}>
                <Text style={[styles.summaryVal, { color: COLORS.healthy }]}>{volunteers.filter(v => v.status === 'active').length}</Text>
                <Text style={styles.summaryLbl}>Active</Text>
              </View>
            </View>
            <Text style={styles.sectionLabel}>LEADERBOARD</Text>
          </View>
        )}
        ListEmptyComponent={() => (
          <View style={styles.empty}>
            <Icon name="account-group-outline" size={44} color={COLORS.border} />
            <Text style={styles.emptyTitle}>No volunteers yet</Text>
          </View>
        )}
        renderItem={({ item, index }) => (
          <View style={styles.volRow}>
            <Text style={styles.rank}>#{index + 1}</Text>
            <View style={[styles.avatar, { backgroundColor: index === 0 ? '#FEF3C7' : COLORS.brandLight }]}>
              <Text style={[styles.avatarText, { color: index === 0 ? '#D97706' : COLORS.brand }]}>
                {item.name.charAt(0).toUpperCase()}
              </Text>
            </View>
            <View style={styles.volInfo}>
              <Text style={styles.volName}>{item.name}</Text>
              <View style={styles.barWrap}>
                <View style={[styles.barFill, { width: `${Math.round((item.totalHoursLogged || 0) / maxHours * 100)}%`, backgroundColor: index === 0 ? '#F59E0B' : COLORS.brand }]} />
              </View>
            </View>
            <View style={styles.volStats}>
              <Text style={styles.volHours}>{(item.totalHoursLogged || 0).toFixed(0)}h</Text>
              <Text style={styles.volShifts}>{item.totalShiftsCompleted || 0} shifts</Text>
            </View>
          </View>
        )}
      />
    </SafeAreaView>
  );
};

const styles = StyleSheet.create({
  safe:  { flex: 1, backgroundColor: COLORS.background },
  topBar: { flexDirection: 'row', alignItems: 'center', gap: SPACING.sm, backgroundColor: COLORS.surface, paddingHorizontal: SPACING.md, paddingVertical: SPACING.sm, borderBottomWidth: 1, borderBottomColor: COLORS.border },
  topTitle: { flex: 1, fontSize: 15, fontWeight: '700', color: COLORS.textPrimary },
  shareBtn: { flexDirection: 'row', alignItems: 'center', gap: 4, backgroundColor: '#0891B2', paddingHorizontal: 14, paddingVertical: 8, borderRadius: RADIUS.lg },
  shareBtnText: { color: '#fff', fontWeight: '700', fontSize: 12 },
  list: { padding: SPACING.md, gap: SPACING.sm },
  summaryRow: { flexDirection: 'row', gap: SPACING.sm, marginBottom: SPACING.md },
  summaryBox: { flex: 1, borderRadius: RADIUS.lg, padding: SPACING.md, alignItems: 'center', gap: 2 },
  summaryVal: { fontSize: 24, fontWeight: '800' },
  summaryLbl: { fontSize: 10, color: COLORS.textSecondary, fontWeight: '600' },
  sectionLabel: { fontSize: 11, fontWeight: '700', color: COLORS.textMuted, letterSpacing: 0.8, marginBottom: SPACING.sm },
  volRow: { flexDirection: 'row', alignItems: 'center', gap: SPACING.sm, backgroundColor: COLORS.surface, borderRadius: RADIUS.lg, padding: SPACING.md, ...SHADOW.card },
  rank: { fontSize: 14, fontWeight: '800', color: COLORS.textMuted, width: 28 },
  avatar: { width: 38, height: 38, borderRadius: 19, alignItems: 'center', justifyContent: 'center' },
  avatarText: { fontSize: 16, fontWeight: '700' },
  volInfo: { flex: 1, gap: 4 },
  volName: { fontSize: 13, fontWeight: '700', color: COLORS.textPrimary },
  barWrap: { height: 6, backgroundColor: COLORS.borderLight, borderRadius: 3, overflow: 'hidden' },
  barFill: { height: '100%', borderRadius: 3 },
  volStats: { alignItems: 'flex-end' },
  volHours: { fontSize: 15, fontWeight: '800', color: COLORS.textPrimary },
  volShifts: { fontSize: 10, color: COLORS.textSecondary },
  empty: { alignItems: 'center', paddingTop: 60, gap: SPACING.sm },
  emptyTitle: { fontSize: 15, fontWeight: '700', color: COLORS.textPrimary },
});

export default VolunteerHoursReportScreen;
