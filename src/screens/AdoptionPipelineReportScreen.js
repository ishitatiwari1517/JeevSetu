// ─── AdoptionPipelineReportScreen ────────────────────────────────────────────
import React, { useCallback, useState } from 'react';
import { View, Text, StyleSheet, ScrollView, TouchableOpacity, StatusBar, Share, RefreshControl } from 'react-native';
import { SafeAreaView } from 'react-native-safe-area-context';
import { useFocusEffect } from '@react-navigation/native';
import Icon from 'react-native-vector-icons/MaterialCommunityIcons';
import { COLORS, SPACING, RADIUS, SHADOW } from '../theme/colors';
import { listAdoptionApplications } from '../services/adoptionService';
import { getOrganization } from '../services/orgService';

const STATUS_CONFIG = [
  { key: 'submitted',    label: 'Submitted',    color: COLORS.brand,     bg: COLORS.brandLight },
  { key: 'under_review', label: 'Under Review', color: COLORS.attention, bg: COLORS.attentionBg },
  { key: 'approved',     label: 'Approved',     color: COLORS.healthy,   bg: COLORS.healthyBg },
  { key: 'home_visit',   label: 'Home Visit',   color: '#7C3AED',        bg: '#EDE9FE' },
  { key: 'completed',    label: 'Adopted',      color: COLORS.healthy,   bg: COLORS.healthyBg },
  { key: 'rejected',     label: 'Rejected',     color: COLORS.critical,  bg: COLORS.criticalBg },
];

const fmtDate = (iso) => new Date(iso).toLocaleDateString('en-IN', { day: 'numeric', month: 'short' });

const AdoptionPipelineReportScreen = ({ navigation }) => {
  const [apps, setApps]           = useState([]);
  const [org, setOrg]             = useState(null);
  const [refreshing, setRefreshing] = useState(false);

  const loadData = useCallback(async () => {
    try {
      const orgObj = await getOrganization();
      setOrg(orgObj);
      setApps(await listAdoptionApplications(orgObj?.id || 'default'));
    } catch (e) { console.warn(e); }
    finally { setRefreshing(false); }
  }, []);

  useFocusEffect(useCallback(() => { loadData(); }, [loadData]));

  const total      = apps.length;
  const completed  = apps.filter(a => a.status === 'completed').length;
  const successRate = total > 0 ? Math.round((completed / total) * 100) : 0;
  const byStatus   = STATUS_CONFIG.map(s => ({ ...s, count: apps.filter(a => a.status === s.key).length }));

  const handleShare = async () => {
    const lines = [
      `ADOPTION PIPELINE REPORT`,
      `${org?.name || 'Shelter'} — ${new Date().toLocaleDateString('en-IN')}`,
      ``,
      `Total applications: ${total}`,
      `Success rate: ${successRate}%`,
      ``,
      ...byStatus.map(s => `  ${s.label}: ${s.count}`),
      ``,
      `Generated by JeevSetu`,
    ];
    await Share.share({ message: lines.join('\n'), title: 'Adoption Pipeline' });
  };

  return (
    <SafeAreaView style={styles.safe} edges={['top']}>
      <StatusBar barStyle="dark-content" backgroundColor={COLORS.surface} />
      <View style={styles.topBar}>
        <TouchableOpacity onPress={() => navigation.goBack()} style={{ padding: 4 }}>
          <Icon name="arrow-left" size={22} color={COLORS.textPrimary} />
        </TouchableOpacity>
        <Text style={styles.topTitle}>Adoption Pipeline</Text>
        <TouchableOpacity style={styles.shareBtn} onPress={handleShare}>
          <Icon name="share-variant" size={18} color="#fff" />
          <Text style={styles.shareBtnText}>Share</Text>
        </TouchableOpacity>
      </View>

      <ScrollView contentContainerStyle={styles.content} showsVerticalScrollIndicator={false}
        refreshControl={<RefreshControl refreshing={refreshing} onRefresh={() => { setRefreshing(true); loadData(); }} tintColor={COLORS.brand} />}>

        {/* Hero stats */}
        <View style={styles.heroRow}>
          <View style={[styles.heroCard, { backgroundColor: '#EDE9FE' }]}>
            <Text style={[styles.heroVal, { color: '#7C3AED' }]}>{total}</Text>
            <Text style={styles.heroLbl}>Total Applications</Text>
          </View>
          <View style={[styles.heroCard, { backgroundColor: COLORS.healthyBg }]}>
            <Text style={[styles.heroVal, { color: COLORS.healthy }]}>{successRate}%</Text>
            <Text style={styles.heroLbl}>Success Rate</Text>
          </View>
        </View>

        {/* Pipeline funnel */}
        <View style={styles.funnelCard}>
          <Text style={styles.funnelTitle}>PIPELINE STATUS</Text>
          {byStatus.map(s => (
            <View key={s.key} style={styles.funnelRow}>
              <View style={[styles.funnelDot, { backgroundColor: s.color }]} />
              <Text style={styles.funnelLabel}>{s.label}</Text>
              <View style={styles.funnelBarWrap}>
                <View style={[styles.funnelBarFill, { width: total > 0 ? `${Math.round(s.count / total * 100)}%` : '0%', backgroundColor: s.color }]} />
              </View>
              <Text style={[styles.funnelCount, { color: s.color }]}>{s.count}</Text>
            </View>
          ))}
        </View>

        {/* Recent applications */}
        {apps.length > 0 && (
          <View style={styles.recentCard}>
            <Text style={styles.recentTitle}>RECENT APPLICATIONS</Text>
            {apps.slice(0, 8).map(a => {
              const sc = STATUS_CONFIG.find(s => s.key === a.status);
              return (
                <View key={a.id} style={styles.appRow}>
                  <View style={{ flex: 1 }}>
                    <Text style={styles.appName}>{a.applicantName}</Text>
                    <Text style={styles.appAnimal}>{a.animalName || 'Animal'} · {a.animalCaseId}</Text>
                  </View>
                  <View style={[styles.statusPill, { backgroundColor: sc?.bg || COLORS.neutralBg }]}>
                    <Text style={[styles.statusPillText, { color: sc?.color || COLORS.neutral }]}>{sc?.label || a.status}</Text>
                  </View>
                  <Text style={styles.appDate}>{fmtDate(a.submittedAt)}</Text>
                </View>
              );
            })}
          </View>
        )}

        {apps.length === 0 && (
          <View style={styles.empty}>
            <Icon name="heart-outline" size={44} color={COLORS.border} />
            <Text style={styles.emptyTitle}>No applications yet</Text>
            <Text style={styles.emptySub}>Mark animals as adoption-ready to start receiving applications.</Text>
          </View>
        )}

        <View style={{ height: SPACING.xl }} />
      </ScrollView>
    </SafeAreaView>
  );
};

const styles = StyleSheet.create({
  safe:  { flex: 1, backgroundColor: COLORS.background },
  topBar: { flexDirection: 'row', alignItems: 'center', gap: SPACING.sm, backgroundColor: COLORS.surface, paddingHorizontal: SPACING.md, paddingVertical: SPACING.sm, borderBottomWidth: 1, borderBottomColor: COLORS.border },
  topTitle: { flex: 1, fontSize: 15, fontWeight: '700', color: COLORS.textPrimary },
  shareBtn: { flexDirection: 'row', alignItems: 'center', gap: 4, backgroundColor: '#7C3AED', paddingHorizontal: 14, paddingVertical: 8, borderRadius: RADIUS.lg },
  shareBtnText: { color: '#fff', fontWeight: '700', fontSize: 12 },
  content: { padding: SPACING.md, gap: SPACING.md },
  heroRow: { flexDirection: 'row', gap: SPACING.sm },
  heroCard: { flex: 1, borderRadius: RADIUS.lg, padding: SPACING.lg, alignItems: 'center', gap: 4 },
  heroVal: { fontSize: 40, fontWeight: '900' },
  heroLbl: { fontSize: 12, color: COLORS.textSecondary, fontWeight: '600', textAlign: 'center' },
  funnelCard: { backgroundColor: COLORS.surface, borderRadius: RADIUS.lg, padding: SPACING.md, ...SHADOW.card, gap: SPACING.sm },
  funnelTitle: { fontSize: 11, fontWeight: '700', color: COLORS.textMuted, letterSpacing: 0.6, marginBottom: 4 },
  funnelRow: { flexDirection: 'row', alignItems: 'center', gap: SPACING.sm },
  funnelDot: { width: 8, height: 8, borderRadius: 4 },
  funnelLabel: { width: 100, fontSize: 12, color: COLORS.textPrimary },
  funnelBarWrap: { flex: 1, height: 8, backgroundColor: COLORS.borderLight, borderRadius: 4, overflow: 'hidden' },
  funnelBarFill: { height: '100%', borderRadius: 4 },
  funnelCount: { width: 24, fontSize: 13, fontWeight: '700', textAlign: 'right' },
  recentCard: { backgroundColor: COLORS.surface, borderRadius: RADIUS.lg, padding: SPACING.md, ...SHADOW.card },
  recentTitle: { fontSize: 11, fontWeight: '700', color: COLORS.textMuted, letterSpacing: 0.6, marginBottom: SPACING.sm },
  appRow: { flexDirection: 'row', alignItems: 'center', gap: SPACING.sm, paddingVertical: 10, borderBottomWidth: 1, borderBottomColor: COLORS.borderLight },
  appName: { fontSize: 13, fontWeight: '700', color: COLORS.textPrimary },
  appAnimal: { fontSize: 11, color: COLORS.brand, marginTop: 1 },
  statusPill: { paddingHorizontal: 8, paddingVertical: 3, borderRadius: RADIUS.full },
  statusPillText: { fontSize: 9, fontWeight: '700' },
  appDate: { fontSize: 10, color: COLORS.textMuted, width: 50, textAlign: 'right' },
  empty: { alignItems: 'center', paddingTop: 60, gap: SPACING.sm },
  emptyTitle: { fontSize: 15, fontWeight: '700', color: COLORS.textPrimary },
  emptySub: { fontSize: 13, color: COLORS.textSecondary, textAlign: 'center', paddingHorizontal: 30 },
});

export default AdoptionPipelineReportScreen;
