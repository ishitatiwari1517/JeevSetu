// ─── AnimalStatusReportScreen ─────────────────────────────────────────────────
// Live animal roster breakdown by species, status, and health — shareable.

import React, { useCallback, useState } from 'react';
import {
  View, Text, StyleSheet, ScrollView, TouchableOpacity,
  StatusBar, Share, RefreshControl,
} from 'react-native';
import { SafeAreaView } from 'react-native-safe-area-context';
import { useFocusEffect } from '@react-navigation/native';
import Icon from 'react-native-vector-icons/MaterialCommunityIcons';
import { COLORS, SPACING, RADIUS, SHADOW } from '../theme/colors';
import { listAnimals } from '../services/animalService';
import { getOrganization } from '../services/orgService';

const capitalize = (s) => s ? s.charAt(0).toUpperCase() + s.slice(1) : '—';

const RowBar = ({ label, value, total, color }) => {
  const pct = total > 0 ? value / total : 0;
  return (
    <View style={styles.rowBar}>
      <Text style={styles.rowLabel}>{capitalize(label)}</Text>
      <View style={styles.barWrap}>
        <View style={[styles.barFill, { width: `${Math.round(pct * 100)}%`, backgroundColor: color }]} />
      </View>
      <Text style={[styles.rowValue, { color }]}>{value}</Text>
    </View>
  );
};

const Section = ({ title, children }) => (
  <View style={styles.section}>
    <Text style={styles.sectionTitle}>{title}</Text>
    {children}
  </View>
);

const AnimalStatusReportScreen = ({ route, navigation }) => {
  const [animals, setAnimals]     = useState([]);
  const [org, setOrg]             = useState(null);
  const [refreshing, setRefreshing] = useState(false);
  const generated = new Date().toLocaleString('en-IN', { day: 'numeric', month: 'long', year: 'numeric', hour: '2-digit', minute: '2-digit' });

  const loadData = useCallback(async () => {
    try {
      const [a, o] = await Promise.all([listAnimals(), getOrganization()]);
      setAnimals(a);
      setOrg(o);
    } catch (e) { console.warn(e); }
    finally { setRefreshing(false); }
  }, []);

  useFocusEffect(useCallback(() => { loadData(); }, [loadData]));

  // Aggregations
  const total = animals.length;
  const byStatus   = {};
  const bySpecies  = {};
  const byHealth   = {};
  for (const a of animals) {
    byStatus[a.status]               = (byStatus[a.status] || 0) + 1;
    bySpecies[a.species]             = (bySpecies[a.species] || 0) + 1;
    byHealth[a.healthStatus || 'unknown'] = (byHealth[a.healthStatus || 'unknown'] || 0) + 1;
  }

  const handleShare = async () => {
    const lines = [
      `ANIMAL STATUS REPORT`,
      `${org?.name || 'Shelter'} — Generated ${generated}`,
      ``,
      `TOTAL ANIMALS: ${total}`,
      ``,
      `BY STATUS:`,
      ...Object.entries(byStatus).map(([k, v]) => `  ${capitalize(k)}: ${v}`),
      ``,
      `BY SPECIES:`,
      ...Object.entries(bySpecies).map(([k, v]) => `  ${capitalize(k)}: ${v}`),
      ``,
      `BY HEALTH:`,
      ...Object.entries(byHealth).map(([k, v]) => `  ${capitalize(k)}: ${v}`),
      ``,
      `Generated by PetVue`,
    ];
    await Share.share({ message: lines.join('\n'), title: 'Animal Status Report' });
  };

  const STATUS_COLORS = { intake: COLORS.brand, available: COLORS.healthy, adopted: '#7C3AED', medical_hold: COLORS.attention, critical: COLORS.critical, transferred: COLORS.neutral, deceased: '#6B7280' };
  const HEALTH_COLORS = { healthy: COLORS.healthy, needs_attention: COLORS.attention, critical: COLORS.critical, stable: COLORS.brand, unknown: COLORS.neutral };

  return (
    <SafeAreaView style={styles.safe} edges={['top']}>
      <StatusBar barStyle="dark-content" backgroundColor={COLORS.surface} />
      <View style={styles.topBar}>
        <TouchableOpacity onPress={() => navigation.goBack()} style={{ padding: 4 }}>
          <Icon name="arrow-left" size={22} color={COLORS.textPrimary} />
        </TouchableOpacity>
        <Text style={styles.topTitle}>Animal Status Report</Text>
        <TouchableOpacity style={styles.shareBtn} onPress={handleShare}>
          <Icon name="share-variant" size={18} color={COLORS.textOnBrand} />
          <Text style={styles.shareBtnText}>Share</Text>
        </TouchableOpacity>
      </View>

      <ScrollView contentContainerStyle={styles.content} showsVerticalScrollIndicator={false}
        refreshControl={<RefreshControl refreshing={refreshing} onRefresh={() => { setRefreshing(true); loadData(); }} tintColor={COLORS.brand} />}>

        {/* Meta */}
        <View style={styles.metaCard}>
          <Text style={styles.metaOrg}>{org?.name || 'Your Shelter'}</Text>
          <Text style={styles.metaDate}>Generated: {generated}</Text>
        </View>

        {/* Hero stat */}
        <View style={styles.heroCard}>
          <Text style={styles.heroValue}>{total}</Text>
          <Text style={styles.heroLabel}>Total Animals in Care</Text>
        </View>

        <Section title="BY STATUS">
          {Object.entries(byStatus).map(([k, v]) => (
            <RowBar key={k} label={k.replace('_', ' ')} value={v} total={total} color={STATUS_COLORS[k] || COLORS.brand} />
          ))}
          {Object.keys(byStatus).length === 0 && <Text style={styles.emptyText}>No animals registered</Text>}
        </Section>

        <Section title="BY SPECIES">
          {Object.entries(bySpecies).map(([k, v]) => (
            <RowBar key={k} label={k} value={v} total={total} color={COLORS.brand} />
          ))}
        </Section>

        <Section title="BY HEALTH STATUS">
          {Object.entries(byHealth).map(([k, v]) => (
            <RowBar key={k} label={k.replace('_', ' ')} value={v} total={total} color={HEALTH_COLORS[k] || COLORS.neutral} />
          ))}
        </Section>

        <View style={{ height: SPACING.xl }} />
      </ScrollView>
    </SafeAreaView>
  );
};

const styles = StyleSheet.create({
  safe:     { flex: 1, backgroundColor: COLORS.background },
  topBar:   { flexDirection: 'row', alignItems: 'center', gap: SPACING.sm, backgroundColor: COLORS.surface, paddingHorizontal: SPACING.md, paddingVertical: SPACING.sm, borderBottomWidth: 1, borderBottomColor: COLORS.border },
  topTitle: { flex: 1, fontSize: 15, fontWeight: '700', color: COLORS.textPrimary },
  shareBtn: { flexDirection: 'row', alignItems: 'center', gap: 4, backgroundColor: COLORS.brand, paddingHorizontal: 14, paddingVertical: 8, borderRadius: RADIUS.lg },
  shareBtnText: { color: COLORS.textOnBrand, fontWeight: '700', fontSize: 12 },
  content:  { padding: SPACING.md, gap: SPACING.md },
  metaCard: { backgroundColor: COLORS.surface, borderRadius: RADIUS.lg, padding: SPACING.md, ...SHADOW.card },
  metaOrg:  { fontSize: 16, fontWeight: '800', color: COLORS.textPrimary },
  metaDate: { fontSize: 12, color: COLORS.textSecondary, marginTop: 2 },
  heroCard: { backgroundColor: COLORS.brandLight, borderRadius: RADIUS.xl, padding: SPACING.lg, alignItems: 'center', borderWidth: 1, borderColor: COLORS.brandMuted },
  heroValue: { fontSize: 56, fontWeight: '900', color: COLORS.brand },
  heroLabel: { fontSize: 14, fontWeight: '600', color: COLORS.brandDark, marginTop: 4 },
  section:   { backgroundColor: COLORS.surface, borderRadius: RADIUS.lg, padding: SPACING.md, gap: SPACING.sm, ...SHADOW.card },
  sectionTitle: { fontSize: 11, fontWeight: '700', color: COLORS.textMuted, letterSpacing: 0.8, marginBottom: 4 },
  rowBar:    { flexDirection: 'row', alignItems: 'center', gap: SPACING.sm },
  rowLabel:  { width: 110, fontSize: 13, color: COLORS.textPrimary },
  barWrap:   { flex: 1, height: 8, backgroundColor: COLORS.borderLight, borderRadius: 4, overflow: 'hidden' },
  barFill:   { height: '100%', borderRadius: 4 },
  rowValue:  { width: 28, fontSize: 13, fontWeight: '700', textAlign: 'right' },
  emptyText: { fontSize: 13, color: COLORS.textMuted, fontStyle: 'italic' },
});

export default AnimalStatusReportScreen;
