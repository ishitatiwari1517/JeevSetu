// ─── VaccinationReportScreen ─────────────────────────────────────────────────
// Animals due or overdue for vaccinations — shareable list.

import React, { useCallback, useState } from 'react';
import {
  View, Text, StyleSheet, FlatList, TouchableOpacity,
  StatusBar, Share, RefreshControl,
} from 'react-native';
import { SafeAreaView } from 'react-native-safe-area-context';
import { useFocusEffect } from '@react-navigation/native';
import Icon from 'react-native-vector-icons/MaterialCommunityIcons';
import { COLORS, SPACING, RADIUS, SHADOW } from '../theme/colors';
import { listAnimals } from '../services/animalService';
import { listAllMedicalRecordsByAnimal } from '../services/medicalRecordService';
import { getOrganization } from '../services/orgService';

const SPECIES_VACCINE_MAP = {
  dog:     ['Rabies', 'Distemper', 'Parvovirus', 'Hepatitis', 'Bordetella'],
  cat:     ['Rabies', 'Feline Panleukopenia', 'Feline Herpesvirus', 'Calicivirus'],
  cow:     ['FMD', 'Brucellosis', 'BVD', 'Leptospirosis'],
  buffalo: ['FMD', 'Brucellosis', 'BVD', 'Haemorrhagic Septicaemia'],
  horse:   ['Tetanus', 'Influenza', 'EHV', 'West Nile'],
  rabbit:  ['RHDV', 'Myxomatosis'],
  bird:    ['Newcastle Disease', 'Avian Influenza'],
  other:   ['Rabies'],
};

const VaccinationReportScreen = ({ route, navigation }) => {
  const [data, setData]           = useState([]);
  const [org, setOrg]             = useState(null);
  const [filter, setFilter]       = useState('all'); // 'all' | 'overdue' | 'missing'
  const [refreshing, setRefreshing] = useState(false);

  const loadData = useCallback(async () => {
    try {
      const orgObj = await getOrganization();
      setOrg(orgObj);
      const oid = orgObj?.id || 'default';

      // OPTIMIZED: 1 read for all records, not N reads
      const [animals, recordsByAnimalId] = await Promise.all([
        listAnimals(),
        listAllMedicalRecordsByAnimal(oid),
      ]);

      const rows = [];
      animals.forEach((animal) => {
        const records = recordsByAnimalId[animal.id] || [];
        const vacRecords = records.filter(r => r.recordType === 'vaccination');
        const givenVaccines = new Set(vacRecords.map(r => r.title.toLowerCase()));
        const expected = SPECIES_VACCINE_MAP[animal.species] || SPECIES_VACCINE_MAP.other;
        const missing = expected.filter(v => !givenVaccines.has(v.toLowerCase()));

        if (missing.length > 0 || !animal.isVaccinated) {
          rows.push({
            id: animal.id,
            caseId: animal.caseId,
            name: animal.name || 'Unknown',
            species: animal.species,
            givenCount: vacRecords.length,
            missingVaccines: missing,
            lastVaccinationDate: vacRecords.length > 0
              ? new Date(Math.max(...vacRecords.map(r => new Date(r.recordedAt)))).toLocaleDateString('en-IN', { day: 'numeric', month: 'short' })
              : null,
            isOverdue: !animal.isVaccinated && vacRecords.length === 0,
          });
        }
      });

      setData(rows);
    } catch (e) { console.warn('VacReport error:', e); }
    finally { setRefreshing(false); }
  }, []);

  useFocusEffect(useCallback(() => { loadData(); }, [loadData]));

  const displayed = filter === 'overdue' ? data.filter(d => d.isOverdue)
                  : filter === 'missing' ? data.filter(d => d.missingVaccines.length > 0)
                  : data;

  const handleShare = async () => {
    const lines = [
      `VACCINATION REPORT`,
      `${org?.name || 'Shelter'} — ${new Date().toLocaleDateString('en-IN')}`,
      ``,
      `Animals needing vaccination: ${data.length}`,
      ``,
      ...data.map(d => [
        `${d.name} (${d.caseId}) — ${d.species}`,
        d.missingVaccines.length ? `  Missing: ${d.missingVaccines.join(', ')}` : '',
        d.lastVaccinationDate ? `  Last vaccine: ${d.lastVaccinationDate}` : `  No vaccines on record`,
      ].filter(Boolean).join('\n')),
      ``,
      `Generated by PetVue`,
    ];
    await Share.share({ message: lines.join('\n'), title: 'Vaccination Report' });
  };

  const renderItem = ({ item }) => (
    <View style={styles.card}>
      <View style={styles.cardHeader}>
        <View style={[styles.dot, { backgroundColor: item.isOverdue ? COLORS.critical : COLORS.attention }]} />
        <View style={{ flex: 1 }}>
          <Text style={styles.cardName}>{item.name} <Text style={styles.cardCaseId}>· {item.caseId}</Text></Text>
          <Text style={styles.cardSpecies}>{item.species}</Text>
        </View>
        {item.lastVaccinationDate && (
          <Text style={styles.lastDate}>Last: {item.lastVaccinationDate}</Text>
        )}
        {!item.lastVaccinationDate && (
          <View style={styles.overdueBadge}>
            <Text style={styles.overdueBadgeText}>Never</Text>
          </View>
        )}
      </View>
      {item.missingVaccines.length > 0 && (
        <View style={styles.missingList}>
          <Text style={styles.missingLabel}>Missing vaccines:</Text>
          <View style={styles.vaccineRow}>
            {item.missingVaccines.map(v => (
              <View key={v} style={styles.vaccinePill}>
                <Text style={styles.vaccinePillText}>{v}</Text>
              </View>
            ))}
          </View>
        </View>
      )}
    </View>
  );

  return (
    <SafeAreaView style={styles.safe} edges={['top']}>
      <StatusBar barStyle="dark-content" backgroundColor={COLORS.surface} />
      <View style={styles.topBar}>
        <TouchableOpacity onPress={() => navigation.goBack()} style={{ padding: 4 }}>
          <Icon name="arrow-left" size={22} color={COLORS.textPrimary} />
        </TouchableOpacity>
        <Text style={styles.topTitle}>Vaccination Report</Text>
        <TouchableOpacity style={styles.shareBtn} onPress={handleShare}>
          <Icon name="share-variant" size={18} color={COLORS.textOnBrand} />
          <Text style={styles.shareBtnText}>Share</Text>
        </TouchableOpacity>
      </View>

      <FlatList
        data={displayed}
        keyExtractor={i => i.id}
        renderItem={renderItem}
        contentContainerStyle={styles.list}
        showsVerticalScrollIndicator={false}
        refreshControl={<RefreshControl refreshing={refreshing} onRefresh={() => { setRefreshing(true); loadData(); }} tintColor={COLORS.brand} />}
        ListHeaderComponent={() => (
          <View>
            <View style={styles.summaryBox}>
              <Icon name="needle" size={28} color={COLORS.attention} />
              <Text style={[styles.summaryNumber, { color: COLORS.attention }]}>{data.length}</Text>
              <Text style={styles.summaryText}>animals need vaccination</Text>
            </View>
            <View style={styles.filterRow}>
              {[['all', 'All'], ['overdue', '🔴 Overdue'], ['missing', '⚠️ Missing']].map(([key, label]) => (
                <TouchableOpacity key={key} style={[styles.chip, filter === key && styles.chipActive]} onPress={() => setFilter(key)}>
                  <Text style={[styles.chipText, filter === key && styles.chipTextActive]}>{label}</Text>
                </TouchableOpacity>
              ))}
            </View>
          </View>
        )}
        ListEmptyComponent={() => (
          <View style={styles.empty}>
            <Icon name="needle" size={44} color={COLORS.border} />
            <Text style={styles.emptyTitle}>All up to date!</Text>
            <Text style={styles.emptySub}>No animals have missing vaccinations.</Text>
          </View>
        )}
      />
    </SafeAreaView>
  );
};

const styles = StyleSheet.create({
  safe:  { flex: 1, backgroundColor: COLORS.background },
  topBar: { flexDirection: 'row', alignItems: 'center', gap: SPACING.sm, backgroundColor: COLORS.surface, paddingHorizontal: SPACING.md, paddingVertical: SPACING.sm, borderBottomWidth: 1, borderBottomColor: COLORS.border },
  topTitle: { flex: 1, fontSize: 15, fontWeight: '700', color: COLORS.textPrimary },
  shareBtn: { flexDirection: 'row', alignItems: 'center', gap: 4, backgroundColor: COLORS.attention, paddingHorizontal: 14, paddingVertical: 8, borderRadius: RADIUS.lg },
  shareBtnText: { color: '#fff', fontWeight: '700', fontSize: 12 },
  list:  { padding: SPACING.md, gap: SPACING.sm },
  summaryBox: { backgroundColor: COLORS.attentionBg, borderRadius: RADIUS.lg, padding: SPACING.lg, alignItems: 'center', gap: 4, marginBottom: SPACING.sm, borderWidth: 1, borderColor: COLORS.attention + '30' },
  summaryNumber: { fontSize: 40, fontWeight: '900' },
  summaryText: { fontSize: 13, color: COLORS.textSecondary },
  filterRow: { flexDirection: 'row', gap: SPACING.sm, marginBottom: SPACING.sm },
  chip: { paddingHorizontal: 14, paddingVertical: 7, borderRadius: RADIUS.full, backgroundColor: COLORS.surface, borderWidth: 1.5, borderColor: COLORS.border },
  chipActive: { backgroundColor: COLORS.attention, borderColor: COLORS.attention },
  chipText: { fontSize: 12, fontWeight: '600', color: COLORS.textSecondary },
  chipTextActive: { color: '#fff' },
  card: { backgroundColor: COLORS.surface, borderRadius: RADIUS.lg, padding: SPACING.md, ...SHADOW.card, gap: SPACING.sm },
  cardHeader: { flexDirection: 'row', alignItems: 'flex-start', gap: SPACING.sm },
  dot: { width: 10, height: 10, borderRadius: 5, marginTop: 4 },
  cardName: { fontSize: 14, fontWeight: '700', color: COLORS.textPrimary },
  cardCaseId: { fontSize: 12, color: COLORS.textSecondary, fontWeight: '400' },
  cardSpecies: { fontSize: 12, color: COLORS.textSecondary, marginTop: 2 },
  lastDate: { fontSize: 11, color: COLORS.textMuted },
  overdueBadge: { backgroundColor: COLORS.criticalBg, paddingHorizontal: 8, paddingVertical: 3, borderRadius: RADIUS.full },
  overdueBadgeText: { fontSize: 10, fontWeight: '700', color: COLORS.critical },
  missingList: { paddingTop: SPACING.sm, borderTopWidth: 1, borderTopColor: COLORS.borderLight },
  missingLabel: { fontSize: 11, color: COLORS.textMuted, marginBottom: 4 },
  vaccineRow: { flexDirection: 'row', flexWrap: 'wrap', gap: 4 },
  vaccinePill: { backgroundColor: COLORS.attentionBg, paddingHorizontal: 10, paddingVertical: 4, borderRadius: RADIUS.full },
  vaccinePillText: { fontSize: 11, color: COLORS.attention, fontWeight: '600' },
  empty: { alignItems: 'center', paddingTop: 60, gap: SPACING.sm },
  emptyTitle: { fontSize: 16, fontWeight: '700', color: COLORS.textPrimary },
  emptySub: { fontSize: 13, color: COLORS.textSecondary },
});

export default VaccinationReportScreen;
